#define PAYLOAD_S4_MEMORY_SIZE 0x00800000ULL
#define PAYLOAD_S4_MAILBOX_SIZE 0x00010000ULL
#define PAYLOAD_S4_MAILBOX_BASE \
	(PAYLOAD_S4_MEMORY_BASE + PAYLOAD_S4_MEMORY_SIZE - PAYLOAD_S4_MAILBOX_SIZE)
#define PAYLOAD_S4_BIN_BASE PAYLOAD_S4_MEMORY_BASE
#define PAYLOAD_S4_BIN_SIZE (PAYLOAD_S4_MEMORY_SIZE - PAYLOAD_S4_MAILBOX_SIZE)

#endif
