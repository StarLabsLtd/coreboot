/*
 * This dormant slice records only claims with an audited build-time route.
 * Lifecycle owners and their optional observers are separate. This slice has
 * no attested lifecycle observers. A binding count other than one is never
 * dispatch-ready.
 */
#define SMM_APMC_ENABLED_CLAIMS(ENTRY) \
	SMM_APMC_LIFECYCLE_CLAIMS(ENTRY) \
	SMM_APMC_XHCI_CLAIM(ENTRY) \
	SMM_APMC_LEGACY_CLAIM(ENTRY) \
	SMM_APMC_CFR_CLAIM(ENTRY) \
	SMM_APMC_OPAL_CLAIMS(ENTRY) \
	SMM_APMC_ROM_ARMOR_CLAIM(ENTRY) \
	SMM_APMC_SMMINFO_CLAIM(ENTRY) \
	SMM_APMC_SMMSTORE_CLAIM(ENTRY) \
	SMM_APMC_ELOG_CLAIM(ENTRY) \
	SMM_APMC_SPI_CLAIM(ENTRY) \
	SMM_APMC_CAPSULE_CLAIM(ENTRY) \
	SMM_APMC_STARLABS_CLAIM(ENTRY) \
	SMM_APMC_ACER_CLAIM(ENTRY)

struct smm_apmc_descriptor {
	u8 command;
	u8 owner;
	u8 role;
	u8 binding_count;
	u8 observer_count;
	bool reserved;
	bool enabled;
};

enum smm_apmc_owner_outcome {
	SMM_APMC_OWNER_HANDLED,
	SMM_APMC_OWNER_UNREADY,
	SMM_APMC_OWNER_MALFORMED,
	SMM_APMC_OWNER_ERROR,
};

enum smm_apmc_dispatch_result {
	SMM_APMC_UNKNOWN,
	SMM_APMC_CONSUMED_SUCCESS,
	SMM_APMC_CONSUMED_REJECT,
};

enum smm_apmc_dispatch_result smm_apmc_command_classify(u8 command,
	enum smm_apmc_owner_outcome outcome,
	struct smm_apmc_descriptor *descriptor);

